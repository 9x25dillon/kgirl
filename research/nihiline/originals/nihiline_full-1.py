"""
Nihiline Recursion — Full Analysis
==================================
Four moves:

  1. Replace pseudo-random phase scrambling with deterministic chaos
     generated by the system's own state — honest within the numerical
     ontology. The "scrambling" is feedback through a nonlinear map,
     not injected randomness.

  2. Compute S_n as information gain per cycle (Shannon entropy of the
     cycle-trajectory distribution), not as a binary success ratio.

  3. Joint sweep C × nihil fraction: does high-control require less
     nothing than low-control?

  4. Sweep ω_r / ω_d ratio at optimum nihil: find ratios where
     cross-sweeping produces standing/pattern structures vs recursive
     ergodic trajectories. Pattern = closed orbit in phase space.
     Recursion = ergodic filling.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.fft import fft

# ============================================================
# Core simulator with deterministic chaotic phase generation
# ============================================================
def simulate(C, omega_d=2.0, omega_r=3.2, f_nihil=0.10,
             M_strength=0.95, T=30.0, dt=0.001,
             psi0=1.0 + 0j, phase_seed=0.4123):
    """
    Phase of each rebirth kick is generated by a logistic map
    iterated on the prior cycle's pre-nihil state — deterministic,
    bounded, chaotic for r in the chaotic regime. No PRNG.

    The "randomness" of decoherence is the system's own nonlinearity
    feeding back through the substrate.
    """
    period_r = 2*np.pi / omega_r
    nihil_dur = f_nihil * period_r
    nihil_steps = int(nihil_dur / dt)

    t = np.arange(0, T, dt)
    gamma = (1.0 - C) * 4.0

    rebirth_times = np.arange(period_r/2, T, period_r)
    rebirth_idx = (rebirth_times / dt).astype(int)
    rebirth_idx = rebirth_idx[rebirth_idx < len(t)]

    # Logistic-map chaotic regime r in [3.7, 4.0] — fully deterministic
    # Modulated by (1-C): high control = phases stay near attractor;
    # low control = phases scatter chaotically across [0, 2π]
    logistic_r = 3.7 + 0.29 * (1.0 - C)   # higher chaos for low C
    chaos_state = phase_seed

    nihil_mask = np.zeros(len(t), dtype=bool)
    for ri in rebirth_idx:
        nihil_mask[max(0, ri - nihil_steps):ri] = True

    psi = np.zeros(len(t), dtype=complex)
    psi[0] = psi0

    # Pre-compute kicks deterministically by iterating chaos_state
    kick_phases = {}
    for ri in rebirth_idx:
        chaos_state = logistic_r * chaos_state * (1 - chaos_state)
        # Phase = chaos × 2π, modulated by (1-C)
        kick_phases[ri] = (1.0 - C) * 2*np.pi * chaos_state

    for i in range(1, len(t)):
        if nihil_mask[i]:
            psi[i] = 0.0
            continue
        psi[i] = psi[i-1] * np.exp(1j*omega_d*dt) * (1 - gamma*dt)
        if i in kick_phases:
            # Kick phase also coupled to pre-nihil field state — true feedback
            phi_kick = kick_phases[i] + C * np.angle(psi[i-1] + 1e-12)
            psi[i] += M_strength * np.exp(1j * phi_kick)
    return t, psi, rebirth_idx, period_r

# ============================================================
# (1) Information gain per cycle — S_n as Shannon entropy
# ============================================================
def cycle_information_gain(psi, rebirth_idx, dt, n_bins=16):
    """
    For each cycle, build a feature vector from the trajectory between
    successive rebirths (peak |ψ|, mean phase, phase drift, variance).
    Then compute the Shannon entropy of the cycle distribution in
    feature space. Higher H = more information generated per cycle.
    """
    if len(rebirth_idx) < 3:
        return 0.0, []
    features = []
    for k in range(len(rebirth_idx) - 1):
        i0, i1 = rebirth_idx[k], rebirth_idx[k+1]
        seg = psi[i0:i1]
        if len(seg) < 5:
            continue
        amp = np.abs(seg)
        ph  = np.angle(seg)
        features.append([
            amp.max(),
            amp.mean(),
            np.abs(np.mean(np.exp(1j*ph))),
            np.std(np.unwrap(ph)),
        ])
    features = np.array(features)
    if len(features) < 4:
        return 0.0, features

    # Normalize each feature to [0,1]
    f_min = features.min(axis=0)
    f_max = features.max(axis=0)
    f_norm = (features - f_min) / (f_max - f_min + 1e-12)

    # Compute Shannon entropy via 4D histogram
    H, _ = np.histogramdd(f_norm, bins=n_bins, range=[[0,1]]*4)
    p = H.flatten() / H.sum()
    p = p[p > 0]
    S_n = -np.sum(p * np.log2(p))
    return S_n, features

