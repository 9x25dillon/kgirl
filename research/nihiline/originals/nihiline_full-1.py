ergodic_measure = np.zeros(len(ratio_grid))
S_by_ratio = np.zeros(len(ratio_grid))

for k, r in enumerate(ratio_grid):
    omega_r = omega_d_fixed * r
    t, psi, ri, _ = simulate(C=C_use, omega_d=omega_d_fixed, omega_r=omega_r,
                              f_nihil=f_opt, T=40.0)
    # Drop transient
    psi_s = psi[5000:]

    # Poincaré section: sample (Re, Im) at fixed phase of decoherence driver
    period_d_steps = int((2*np.pi/omega_d_fixed)/0.001)
    samples = psi_s[::period_d_steps]
    # Pattern = compact phase-space distribution (closed orbit)
    # Recursion = spread distribution (ergodic)
    if len(samples) > 4:
        spread = np.std(samples.real) + np.std(samples.imag)
        # Pattern indicator: 1/spread (inverse) — high when compact
        pattern_measure[k] = 1.0 / (spread + 0.05)
        # Ergodic indicator: spread itself
        ergodic_measure[k] = spread

    Sn, _ = cycle_information_gain(psi, ri, 0.001)
    S_by_ratio[k] = Sn / 16.0

