# ============================================================
# (2) Joint sweep C × nihil — does high-control need less nothing?
# ============================================================
C_grid = np.linspace(0.30, 0.95, 14)
f_grid = np.linspace(0.0, 0.80, 17)
P_grid = np.zeros((len(C_grid), len(f_grid)))
Sn_grid = np.zeros_like(P_grid)

for i, Cv in enumerate(C_grid):
    for j, fv in enumerate(f_grid):
        t, psi, ri, _ = simulate(C=Cv, f_nihil=fv, T=20.0)
        amp = np.abs(psi)
        ph  = np.angle(psi)
        alive = amp > 0.05
        prod = float(np.mean(alive))
        if alive.sum() > 0:
            coh = np.abs(np.mean(np.exp(1j*ph[alive])))
        else:
            coh = 0.0
        Sn, _ = cycle_information_gain(psi, ri, 0.001)
        # Normalize S_n by log2(bins^features) = log2(16^4) = 16
        Sn_norm = Sn / 16.0
        P_grid[i,j] = Sn_norm * coh * prod
        Sn_grid[i,j] = Sn_norm

# Optimal nihil for each C
f_opt_by_C = f_grid[np.argmax(P_grid, axis=1)]
print("\nOptimal nihil fraction by control level:")
for Cv, fv in zip(C_grid, f_opt_by_C):
    print(f"  C={Cv:.2f}  →  f_opt = {fv:.3f}")

# ============================================================
# (3) ω_r / ω_d ratio sweep — pattern vs recursion
# ============================================================
omega_d_fixed = 2.0
ratio_grid = np.linspace(0.4, 4.5, 80)
